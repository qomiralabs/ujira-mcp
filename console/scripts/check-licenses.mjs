// Fails when any installed package carries a license outside the allowlist:
// production packages against the production list, dev only packages against
// that list plus MPL-2.0. Reads the lockfile, so it checks exactly what
// `npm ci` installs. With --write it also writes THIRD_PARTY_NOTICES.md for
// what ships in the browser bundle.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROD = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'Zlib',
  'Unlicense',
  'CC0-1.0',
  'BlueOak-1.0.0',
  'Python-2.0',
  'OFL-1.1',
]);
const DEV = new Set([...PROD, 'MPL-2.0']);

/** True when an SPDX expression is satisfied by the allowed set. */
function allowed(expression, set) {
  const e = expression.trim().replace(/^\((.*)\)$/, '$1');
  if (/ OR /i.test(e)) return e.split(/ OR /i).some((part) => allowed(part, set));
  if (/ AND /i.test(e)) return e.split(/ AND /i).every((part) => allowed(part, set));
  return set.has(e);
}

const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const problems = [];
const shipped = [];
for (const [path, entry] of Object.entries(lock.packages)) {
  if (path === '') continue;
  const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
  let license = entry.license;
  if (license === undefined) {
    try {
      license = JSON.parse(readFileSync(join(root, path, 'package.json'), 'utf8')).license;
    } catch {
      // Optional platform packages are not installed everywhere.
    }
  }
  if (typeof license !== 'string') {
    if (entry.optional === true) continue;
    problems.push(`${name}@${entry.version}: no license`);
    continue;
  }
  const dev = entry.dev === true;
  if (!allowed(license, dev ? DEV : PROD)) {
    problems.push(`${name}@${entry.version}: ${license} (${dev ? 'dev' : 'production'})`);
  }
  if (!dev) shipped.push({ name, version: entry.version, license });
}

if (process.argv.includes('--write')) {
  shipped.sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    '# Third party notices',
    '',
    'Packages that ship in the UJIRA Console bundle, with their licenses.',
    'Generated by `npm run licenses -- --write`.',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...shipped.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
    'Fonts: Inter and JetBrains Mono, SIL Open Font License 1.1, through Fontsource.',
    'Brand marks, icons and the weave band are Qomira Labs assets.',
    '',
  ];
  writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
}

if (problems.length > 0) {
  process.stderr.write(`License check failed:\n${problems.map((p) => `  ${p}`).join('\n')}\n`);
  process.exit(1);
}
process.stdout.write(
  `License check passed: ${String(shipped.length)} production packages, ${String(
    Object.keys(lock.packages).length - 1 - shipped.length,
  )} dev packages.\n`,
);
