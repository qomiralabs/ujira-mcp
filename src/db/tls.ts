// The TLS trust this module pins. The hosted database is Render Postgres,
// whose external endpoints, both the server on 5432 and its PgBouncer on
// 6432, present a Let's Encrypt certificate. Verification is on, the host
// name is checked against the certificate, and the trust store is the two
// Internet Security Research Group roots below rather than the system
// roots, so a certificate from any other issuer is refused however valid it
// looks.
//
// Two roots, because Let's Encrypt is moving its RSA chain to a new root.
// Measured on 2026-11-27 against the Virginia endpoint, the server sends
// leaf, then the YR2 intermediate, then Root YR cross signed by ISRG Root
// X1, so X1 is what verifies it today. Once the cross signed certificate is
// dropped from the chain, the self signed Root YR verifies it instead. With
// both pinned, that change needs no release.
//
// The PEMs are embedded rather than read from disk, so a built image cannot
// be missing them and nothing resolves a path at run time. The files in
// db/certs/ are the source of truth, and tls.test.ts fails if the two ever
// differ or if the embedded bytes stop being those roots.
//
// Where they came from, because a fingerprint proves identity without saying
// where identity came from:
//
//   https://letsencrypt.org/certs/isrgrootx1.pem
//   https://letsencrypt.org/certs/gen-y/root-yr.pem
//
// Downloaded on 2026-11-27. The X1 fingerprint below matches the copy in
// Node's own root store, a second source. Root YR is not in that store yet;
// its public key matches the key of the cross signed Root YR the server
// sent. Rotating the pin means fetching the URLs again, checking the
// fingerprints against what Let's Encrypt publishes, and updating the files
// and this module, which tls.test.ts requires to agree.
//
// A URL may not carry an ssl parameter, and config.ts refuses one: pg lets
// sslmode replace or disable this, which would quietly undo the pin.

